def upsert_pages(project: dict[str, Any]) -> tuple[dict[str, dict[str, Any]], list[str]]:
    query = urllib.parse.urlencode({"project_id": project["id"]})
    current = request("GET", f"/concept-pages?{query}")
    by_title = {item["title"]: item for item in current}
    results: dict[str, dict[str, Any]] = {}
    actions: list[str] = []
    for entry in [*PLACES, *GENERAL_MONSTERS, *NAMED]:
        existing = by_title.get(entry["title"])
        if not existing:
            existing = next((by_title.get(alias) for alias in entry.get("aliases", []) if by_title.get(alias)), None)
        payload = page_payload(project["id"], entry)
        if existing:
            payload.pop("project_id")
            results[entry["title"]] = request("PATCH", f"/concept-pages/{existing['id']}", payload)
            actions.append(f"수정: {entry['title']}")
        else:
            results[entry["title"]] = request("POST", "/concept-pages", payload)
            actions.append(f"추가: {entry['title']}")
    for title in DEPRECATED_TITLES:
        existing = by_title.get(title)
        if existing:
            request("DELETE", f"/concept-pages/{existing['id']}")
            actions.append(f"삭제: {title}")
    return results, actions


