def request(method: str, path: str, payload: dict[str, Any] | None = None) -> Any:
    data = None if payload is None else json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        f"{API_BASE}{path}",
        data=data,
        method=method,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            raw = response.read()
            return json.loads(raw.decode("utf-8")) if raw else None
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"{method} {path} failed: {exc.code} {detail}") from exc


def lore_doc(sections: list[tuple[str, str]]) -> dict[str, Any]:
    content: list[dict[str, Any]] = []
    for heading, text in sections:
        content.append(
            {
                "type": "heading",
                "attrs": {"level": 2},
                "content": [{"type": "text", "text": heading}],
            }
        )
        for paragraph in text.split("\n"):
            if paragraph.strip():
                content.append(
                    {
                        "type": "paragraph",
                        "content": [{"type": "text", "text": paragraph.strip()}],
                    }
                )
    return {"type": "doc", "content": content}


def place(
    title: str,
    act: int,
    summary: str,
    identity: str,
    senses: str,
    traces: str,
    tension: str,
    facts: list[str],
    names: list[str],
    *,
    aliases: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "title": title,
        "aliases": aliases or [],
        "category_key": "place",
        "tags": [f"액트 {act}", "장소", "로어", "정사 근거"],
        "summary": summary,
        "body_json": lore_doc(
            [
                ("장소의 정체", identity),
                ("보이는 것과 느껴지는 것", senses),
                ("남아 있는 흔적과 관계", traces),
                ("로어 작성에 쓸 긴장", tension),
            ]
        ),
        "properties_json": {
            "act": act,
            "entity_type": "location_lore",
            "canon_scope": "Diablo II 액트 I·II",
            "related_names": names,
            "research_basis": RESEARCH_BASIS,
        },
        "locked_facts": facts,
        "open_questions": [],
        "forbidden_changes": ["게임과 공식 설정이 확정하지 않은 과거를 정사로 단정하지 않는다."],
    }


